#include "../../minirt.h"

uint	id_set(uint group, int id)
{
	return ((group << 24) | (id & 0x00ffffff));
}

uint	id_group_get(int id)
{
	if (id < 0)
		return (-1);
	return ((id >> 24) & 0xff);
}
